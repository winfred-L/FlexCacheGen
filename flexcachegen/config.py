class Config:
    # model settings
    device = 'cuda:0'

    # generation settings
    temperature: float = 0.0
    max_new_tokens: int = 1024

    # sparsity settings
    sparsity_strategy: str = 'after-prefill' # ['none', 'before-prefill', 'after-prefill']
    sparsity_threshold: str = '0.9'
    pruning_heads: dict[int, list[int]] | None = None # {layer_idx: [head_indices]}
        # when sparsity_strategy is not 'none', pruning_heads is 'none', prune all video kv inplace.

    # offloading settings
    offload_kv_to_cpu: bool = True

    # paged attention settings
    paged_kv: bool = True  # when True, always offload kv to CPU
    block_size: int = 256  # flash_attn requires page_block_size to be a multiple of 256
    block_topk_ratio: float | None = 0.8  # if set (0~1), keep this fraction of blocks per layer during decode
    pipeline_decode: bool = False  # enable DMA/compute overlap pipeline in decode

    # profiling settings
    nsys_nvtx: bool = False  # enable NVTX annotations for nsys profiling


    def __init__(self, model_path: str, **kwargs):
        # TODO: currently only support for qwen3vl-8b
        self.model_path = model_path
        self.hf_config = AutoConfig.from_pretrained(self.model_path)
        
        self.dtype = torch.bfloat16
        self.spatial_merge_size = 2
        self.eos_token_id = (151645, 151643)

        if self.sparsity_strategy != 'none':
            self.pruning_heads = pruning_heads_list[self.sparsity_threshold]

        self.print_settings()
            

    def print_settings(self):
        print("==== Configurations ====")
        print("Model path:", self.model_path)
        print("Device:", self.device)
        print("Temperature:", self.temperature)
        print("Max new tokens:", self.max_new_tokens)
        print("Sparsity strategy:", self.sparsity_strategy)
        if self.sparsity_strategy != 'none':
            print("Sparsity threshold:", self.sparsity_threshold)
            print("Pruning heads:", self.pruning_heads)
        print("Offload KV to CPU:", self.offload_kv_to_cpu)
        print("Paged KV:", self.paged_kv)
        if self.paged_kv:
            print("Block size:", self.block_size)
            print("Block topk ratio:", self.block_topk_ratio)
            print("Pipeline decode:", self.pipeline_decode)
            print("NVTX profiling:", self.nsys_nvtx)
        print("========================")
            

