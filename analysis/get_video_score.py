import torch

video_score = torch.load('/data1/lyc/flexllmgen_outputs/attn_weight/qwen3vl-8b_28s/sum_result_max.pt')
num_layers, num_heads = video_score.shape # 36, 32
num_kv_heads = 8
kv_group_size = num_heads // num_kv_heads

threshold = 0.2
print(f'Pruning heads with video_score <= {threshold}...')

pruning_heads = {layer_idx: [] for layer_idx in range(num_layers)}
for layer_idx in range(num_layers):
    for kv_head_idx in range(num_kv_heads):
        a0 = video_score[layer_idx, kv_head_idx * kv_group_size]
        a1 = video_score[layer_idx, kv_head_idx * kv_group_size + 1]
        a2 = video_score[layer_idx, kv_head_idx * kv_group_size + 2]
        a3 = video_score[layer_idx, kv_head_idx * kv_group_size + 3]

        if a0 > threshold or a1 > threshold or a2 > threshold or a3 > threshold:
            pass
        else:
            pruning_heads[layer_idx].append(kv_head_idx)


print(pruning_heads)

cnt = 0
for layer_idx in range(num_layers):
    cnt += len(pruning_heads[layer_idx])
print(f'Total number of pruned heads: {cnt}')
ratio = cnt / (num_layers * num_kv_heads)
print(f'Pruning ratio: {ratio:.2%}')


